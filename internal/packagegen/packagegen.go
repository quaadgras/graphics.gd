// Package packagegen generates type-safe Go packages for the resources
// inside a graphics.gd project's graphics directory, so that they can be
// referenced from Go with compile-time checking, see
// https://github.com/quaadgras/graphics.gd/discussions/283
//
// Each directory that contains resources gets a graphics.gen.go file with
// one [Resource.Library] declaration per file extension, named after that
// extension:
//
//	var PNG = Resource.Library[struct {
//		Bullet Texture2D.Instance `gd:"res://bullet.png"`
//	}]()
//
// Scene files additionally generate a struct mirroring the layout of their
// scene tree, so that node access is statically checked:
//
//	var TSCN = Resource.Library[struct {
//		Main PackedScene.Is[SceneMain] `gd:"res://main.tscn"`
//	}]()
//
//	type SceneMain struct {
//		Node2D.Instance
//
//		Bullets Node2D.Instance
//	}
package packagegen

