// Header marks a file as generated: files without it are never overwritten
// or removed.
const Header = "// Code generated by graphics.gd. DO NOT EDIT."

// FileName of the file generated in each directory that contains resources.
const FileName = "graphics.gen.go"

// All (re)generates a graphics package in each directory of the given
// resource directory tree that contains resources, removing generated files
// from directories that no longer have any. Resources are loaded through
// their res:// paths, so the engine must be running with root mounted as
// the project directory.
// Directories are independent, so one that cannot be generated (an
// unreadable file, a resource the engine refuses to load) is reported but
// does not stop the rest of the tree from being kept up to date.
func All(root string) error {
	root = filepath.Clean(root)
	var problems []error
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			problems = append(problems, err)
			return nil
		}
		if !d.IsDir() {
			return nil
		}
		if path != root && (strings.HasPrefix(d.Name(), ".") || d.Name() == "addons") {
			return fs.SkipDir
		}
		prefix := "res://"
		rel, err := filepath.Rel(root, path)
		if err == nil && rel != "." {
			prefix += filepath.ToSlash(rel) + "/"
			if !importable(filepath.ToSlash(rel)) {
				// A Go package here could never be imported, so generating
				// one only breaks ./... builds of the project. Clear any
				// file left behind by an earlier name and move on: the
				// resources are still reachable by their res:// paths.
				if err := update(filepath.Join(path, FileName), ""); err != nil {
					problems = append(problems, err)
				}
				return nil
			}
		}
		source, err := Directory(path, prefix, packageName(path))
		if err != nil {
			problems = append(problems, err)
			return nil
		}
		if err := update(filepath.Join(path, FileName), source); err != nil {
			problems = append(problems, err)
		}
		return nil
	})
	if err != nil {
		problems = append(problems, err)
	}
	return errors.Join(problems...)
}

// update writes source to target if it differs from what is already there,
// removing target instead when source is empty. Files that do not carry the
// generated-code [Header] are left alone.
func update(target, source string) error {
	existing, err := os.ReadFile(target)
	if err == nil && !strings.HasPrefix(string(existing), Header) {
		return fmt.Errorf("packagegen: refusing to replace %s: not a generated file", target)
	}
	if source == "" {
		if err == nil {
			return os.Remove(target)
		}
		return nil
	}
	if err == nil && string(existing) == source {
		return nil
	}
	return os.WriteFile(target, []byte(source), 0o644)
}

// Directory generates the graphics package source for the resource files
// directly inside dir (an operating-system path used to list and name the
// files). Each file is loaded from, and tagged with, prefix+name — pass a
// trailing-slash "res://…/" prefix for project directories. Returns the
// empty string if the directory contains no resources.
//
// pkg is the package name to declare; it is sanitized, so a directory
// named after a Go keyword ("interface", "map") still generates a package
// that compiles.
func Directory(dir, prefix, pkg string) (string, error) {
	pkg = goPackageName(pkg)
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	type field struct {
		name  string
		typ   string // empty for scene fields, whose type is named after emission-time renames.
		tag   string
		scene *sceneType
	}
	var (
		groups   = make(map[string][]field)
		scenes   []*sceneType
		siblings = map[string]bool{}
	)
	for _, entry := range entries {
		siblings[entry.Name()] = true
	}
	for _, entry := range entries {
		if entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		ext := strings.ToLower(strings.TrimPrefix(filepath.Ext(entry.Name()), "."))
		// resources either have a runtime loader for their extension, or an
		// .import sidecar recording how the editor imported them.
		if !recognizedExtensions()[ext] && !siblings[entry.Name()+".import"] {
			continue
		}
		path := prefix + entry.Name()
		resource := ResourceLoader.Load(path, "")
		if resource == (Resource.Instance{}) {
			continue
		}
		var (
			name = identifier(strings.TrimSuffix(entry.Name(), filepath.Ext(entry.Name())))
			f    = field{name: name, tag: path}
		)
		if class := gd.ObjectGetClass(resource.AsObject()[0]).String(); class == "PackedScene" {
			// Hand-authored scenes are named Scene<Stem>, imported 3D model
			// formats Model<Stem>, so a JumpingPadModel.tscn beside the
			// JumpingPadModel.glb it instances yields SceneJumpingPadModel
			// and ModelJumpingPad without colliding. A stem's trailing kind
			// word is dropped rather than repeated.
			kind := "Scene"
			switch ext {
			case "glb", "gltf", "fbx", "blend", "dae", "obj":
				kind = "Model"
			}
			stem := name
			if len(stem) > len(kind) {
				stem = strings.TrimSuffix(stem, kind)
			}
			scene := parseScene(Object.To[PackedScene.Instance](resource), kind+stem, path)
			scene.ext = ext
			scenes = append(scenes, scene)
			f.scene = scene
		} else {
			class = friendlyClass(engineClass(class, "Resource"))
			f.typ = class + ".Instance"
		}
		group := identifier(strings.ToUpper(ext))
		groups[group] = append(groups[group], f)
	}
	var constants string
	if prefix == "res://" {
		constants = projectConstants()
	}
	if len(groups) == 0 && constants == "" {
		return "", nil
	}
	// Ties within a kind (a foo.glb beside a foo.gltf) are rare enough that
	// their struct names simply carry the extension.
	byName := map[string][]*sceneType{}
	for _, scene := range scenes {
		byName[scene.name] = append(byName[scene.name], scene)
	}
	for _, colliding := range byName {
		if len(colliding) > 1 {
			for _, scene := range colliding {
				scene.name += identifier(strings.ToUpper(scene.ext))
			}
		}
	}
	// The body is rendered first so that the import block only lists the
	// packages of classes that were actually emitted: name collisions and
	// scene renames would otherwise leave unused imports behind.
	var body strings.Builder
	imports := map[string]bool{}
	var names []string
	for name := range groups {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fields := groups[name]
		sort.Slice(fields, func(i, j int) bool { return fields[i].name < fields[j].name })
		fmt.Fprintf(&body, "var %s = Resource.Library[struct {\n", name)
		seen := map[string]bool{}
		for _, f := range fields {
			if seen[f.name] {
				fmt.Fprintf(&body, "\t// %s skipped: name collides with another %s resource\n", f.tag, name)
				continue
			}
			seen[f.name] = true
			typ := f.typ
			if f.scene != nil {
				typ = "PackedScene.Is[" + f.scene.name + "]"
				imports["PackedScene"] = true
			} else {
				imports[strings.TrimSuffix(typ, ".Instance")] = true
			}
			fmt.Fprintf(&body, "\t%s %s `gd:%q`\n", f.name, typ, f.tag)
		}
		body.WriteString("}]()\n\n")
	}
	sort.Slice(scenes, func(i, j int) bool { return scenes[i].name < scenes[j].name })
	seen := map[string]bool{}
	for _, scene := range scenes {
		if seen[scene.name] {
			continue
		}
		seen[scene.name] = true
		fmt.Fprintf(&body, "type %s struct {\n", scene.name)
		writeNodeBody(&body, scene.root, "\t", scene.path, imports)
		body.WriteString("}\n\n")
	}
	body.WriteString(constants)
	var b strings.Builder
	b.WriteString(Header + "\n\npackage " + pkg + "\n\n")
	if len(groups) > 0 {
		var paths []string
		for class := range imports {
			paths = append(paths, "graphics.gd/classdb/"+class)
		}
		paths = append(paths, "graphics.gd/classdb/Resource")
		sort.Strings(paths)
		b.WriteString("import (\n")
		for _, path := range paths {
			fmt.Fprintf(&b, "\t%q\n", path)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(body.String())
	source, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("packagegen: generated invalid Go for %s: %w", dir, err)
	}
	return string(source), nil
}

// sceneNode is a node in a parsed scene tree, reduced to what the generated
// struct needs: its name, its engine class and its children.
type sceneNode struct {
	name     string
	class    string
	children []*sceneNode
}

type sceneType struct {
	name string
	path string
	ext  string
	root *sceneNode
}

// parseScene walks the packed scene's [SceneState] to recover the tree that
// instantiating it will produce. Nodes of classes defined by an extension
// (including this Go project's own classes, which cannot be referenced from
// generated code without creating an import cycle) are typed as their
// closest engine base class.
func parseScene(packed PackedScene.Instance, name, path string) *sceneType {
	state := SceneState.Instance(PackedScene.Advanced(packed).GetState())
	var root *sceneNode
	byPath := map[string]*sceneNode{}
	for idx := range state.GetNodeCount() {
		class := state.GetNodeType(idx)
		if class == "" { // the node instances another scene, type it as that scene's root.
			if instance := state.GetNodeInstance(idx); instance != (PackedScene.Instance{}) {
				class = SceneState.Instance(PackedScene.Advanced(instance).GetState()).GetNodeType(0)
			}
		}
		node := &sceneNode{
			name:  state.GetNodeName(idx),
			class: engineClass(class, "Node"),
		}
		path := strings.TrimPrefix(state.GetNodePath(idx), "./")
		if idx == 0 || path == "." || path == "" {
			root = node
			byPath["."] = node
			continue
		}
		byPath[path] = node
		parent := "."
		if i := strings.LastIndex(path, "/"); i >= 0 {
			parent = path[:i]
		}
		if p, ok := byPath[parent]; ok {
			p.children = append(p.children, node)
		}
	}
	if root == nil {
		root = &sceneNode{class: "Node"}
	}
	return &sceneType{name: name, path: path, root: root}
}

// writeNodeBody emits the embedded Instance and child fields of a scene
// node, preserving the order the scene stores them in. Children with
// children of their own become nested structs, matching the layout that
// scene-struct binding (see the classdb/Node package) resolves at runtime.
func writeNodeBody(b *strings.Builder, node *sceneNode, indent, source string, imports map[string]bool) {
	imports[node.class] = true
	if source != "" { // the scene the root node comes from.
		fmt.Fprintf(b, "%s%s.Instance `gd:%q`\n", indent, node.class, source)
	} else {
		fmt.Fprintf(b, "%s%s.Instance\n", indent, node.class)
	}
	if len(node.children) > 0 {
		b.WriteString("\n")
	}
	seen := map[string]bool{}
	for _, child := range node.children {
		name := identifier(child.name)
		if seen[name] {
			fmt.Fprintf(b, "%s// node %q skipped: name collides with another child\n", indent, child.name)
			continue
		}
		seen[name] = true
		var tag string
		if name != child.name {
			tag = fmt.Sprintf(" `gd:%q`", child.name)
		}
		if len(child.children) == 0 {
			imports[child.class] = true
			fmt.Fprintf(b, "%s%s %s.Instance%s\n", indent, name, child.class, tag)
		} else {
			fmt.Fprintf(b, "%s%s struct {\n", indent, name)
			writeNodeBody(b, child, indent+"\t", "", imports)
			fmt.Fprintf(b, "%s}%s\n", indent, tag)
		}
	}
}

// projectConstants emits constants for the project-wide names that are
// otherwise stringly-typed at their point of use: input actions, global node
// groups and named layers. Only the root graphics package carries these.
func projectConstants() string {
	var actions, groups []string
	type layer struct {
		name   string
		number int
	}
	var layers []layer
	for _, property := range Object.GetPropertyList(ProjectSettings.Advanced()) {
		switch {
		case strings.HasPrefix(property.Name, "input/"):
			action := strings.TrimPrefix(property.Name, "input/")
			if strings.Contains(action, ".") { // a per-platform feature override, not an action.
				continue
			}
			actions = append(actions, action)
		case strings.HasPrefix(property.Name, "global_group/"):
			groups = append(groups, strings.TrimPrefix(property.Name, "global_group/"))
		case strings.HasPrefix(property.Name, "layer_names/"):
			_, entry, ok := strings.Cut(strings.TrimPrefix(property.Name, "layer_names/"), "/")
			if !ok {
				continue
			}
			number, err := strconv.Atoi(strings.TrimPrefix(entry, "layer_"))
			if err != nil {
				continue
			}
			name, _ := ProjectSettings.GetSetting(property.Name, "").(string)
			if name == "" {
				continue
			}
			layers = append(layers, layer{name: name, number: number})
		}
	}
	var b strings.Builder
	writeConstants := func(category string, names []string, value func(string) string) {
		if len(names) == 0 {
			return
		}
		sort.Strings(names)
		seen := map[string]bool{}
		b.WriteString("const (\n")
		for _, name := range names {
			ident := constant(category, name)
			if seen[ident] {
				continue
			}
			seen[ident] = true
			fmt.Fprintf(&b, "\t%s = %s\n", ident, value(name))
		}
		b.WriteString(")\n\n")
	}
	writeConstants("Action", actions, func(name string) string { return fmt.Sprintf("%q", name) })
	writeConstants("Group", groups, func(name string) string { return fmt.Sprintf("%q", name) })
	if len(layers) > 0 {
		sort.Slice(layers, func(i, j int) bool { return layers[i].name < layers[j].name })
		seen := map[string]bool{}
		b.WriteString("const (\n")
		for _, l := range layers {
			ident := constant("Layer", l.name)
			if seen[ident] {
				fmt.Fprintf(&b, "\t// layer %q skipped: name collides with another layer\n", l.name)
				continue
			}
			seen[ident] = true
			fmt.Fprintf(&b, "\t%s = %d\n", ident, l.number)
		}
		b.WriteString(")\n\n")
	}
	return b.String()
}

// constant reduces name to an exported Go constant identifier prefixed by
// its category: words keep their boundaries with underscores, short words
// become initialisms and words repeating the category are dropped, so
// ("Action", "ui_left") becomes ActionUI_Left and ("Group", "Test Group")
// becomes GroupTest.
func constant(category, name string) string {
	var words []string
	for _, word := range strings.FieldsFunc(name, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	}) {
		if strings.EqualFold(word, category) {
			continue
		}
		if utf8.RuneCountInString(word) <= 2 {
			word = strings.ToUpper(word)
		} else {
			first, size := utf8.DecodeRuneInString(word)
			word = string(unicode.ToUpper(first)) + word[size:]
		}
		words = append(words, word)
	}
	if len(words) == 0 {
		return category + "X"
	}
	return category + strings.Join(words, "_")
}

// friendlyClass maps import-generated concrete classes to the base class
// their resources are used as: png/svg imports produce CompressedTexture2D
// resources, referenced as Texture2D.
var friendly = map[string]string{
	"CompressedTexture2D":      "Texture2D",
	"CompressedTexture2DArray": "Texture2DArray",
	"CompressedTexture3D":      "Texture3D",
	"CompressedTextureLayered": "TextureLayered",
	"CompressedCubemap":        "Cubemap",
	"CompressedCubemapArray":   "CubemapArray",
}

func friendlyClass(class string) string {
	if friendly, ok := friendly[class]; ok {
		return friendly
	}
	return class
}

// engineClass resolves class to the closest class that has a generated
// package under graphics.gd/classdb: extension-defined classes walk up
// their inheritance chain until an engine class is found.
func engineClass(class, fallback string) string {
	for class != "" && ClassDB.ClassExists(class) {
		switch ClassDB.ClassGetApiType(class) {
		case ClassDB.ApiCore, ClassDB.ApiEditor:
			return class
		}
		class = ClassDB.GetParentClass(class)
	}
	return fallback
}

var recognizedExtensions = sync.OnceValue(func() map[string]bool {
	recognized := map[string]bool{}
	for _, ext := range ResourceLoader.GetRecognizedExtensionsForType("Resource") {
		recognized[strings.ToLower(ext)] = true
	}
	// the project's own extension manifest is not a graphics resource.
	delete(recognized, "gdextension")
	return recognized
})

// identifier reduces name to an exported Go identifier: runs of characters
// that cannot appear in one capitalize the letter that follows, so
// "face_happy.png" becomes FaceHappy.
func identifier(name string) string {
	var b strings.Builder
	upper := true
	for _, r := range name {
		switch {
		case unicode.IsLetter(r):
			if upper {
				r = unicode.ToUpper(r)
				upper = false
			}
			b.WriteRune(r)
		case unicode.IsDigit(r):
			if b.Len() == 0 {
				b.WriteRune('X')
			}
			b.WriteRune(r)
			upper = true
		default:
			upper = true
		}
	}
	if b.Len() == 0 {
		return "X"
	}
	return b.String()
}

// importable reports whether a slash-separated project-relative directory
// path can appear inside a Go import path. Asset directories are named for
// artists, not for the toolchain ("Normals Godot-Unity"), and a package in
// one of those is not merely unused: it fails every ./... build of the
// project with "malformed import path".
func importable(rel string) bool {
	for _, elem := range strings.Split(rel, "/") {
		if elem == "" || elem == "." || elem == ".." {
			return false
		}
		for _, r := range elem {
			switch {
			case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			case r == '-' || r == '.' || r == '_' || r == '~':
			default:
				return false
			}
		}
	}
	return true
}

var packageClause = regexp.MustCompile(`(?m)^package\s+(\w+)`)

// goPackageName makes name safe to follow a package clause: directory
// names are not bound by Go's rules, so one that spells a keyword
// ("interface", "map", "default") or the blank identifier gets a trailing
// underscore rather than generating a file that cannot be parsed.
func goPackageName(name string) string {
	if token.IsKeyword(name) {
		return name + "_"
	}
	if !token.IsIdentifier(name) { // empty, blank, or not spellable at all
		return "graphics"
	}
	return name
}

// packageName returns the package name generated files in dir should use:
// the name of any existing hand-written Go package in the directory, or
// else a name derived from the directory itself.
func packageName(dir string) string {
	entries, _ := os.ReadDir(dir)
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || name == FileName {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil || strings.HasPrefix(string(data), Header) {
			continue
		}
		if m := packageClause.FindSubmatch(data); m != nil {
			return string(m[1])
		}
	}
	var b strings.Builder
	for _, r := range strings.ToLower(filepath.Base(dir)) {
		if unicode.IsLetter(r) || r == '_' || (unicode.IsDigit(r) && b.Len() > 0) {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "graphics"
	}
	return b.String()
}
