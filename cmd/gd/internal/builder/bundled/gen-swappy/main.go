// Command gen-swappy regenerates ../swappy, the source of Google's Swappy
// frame pacing library that gd bundles, from the pinned commit of the
// Android Game SDK that Godot's own prebuilt binaries are made from.
//
//	go run ./cmd/gd/internal/builder/bundled/gen-swappy
//
// Godot only links Swappy as a prebuilt static library, built against the
// NDK's C++ standard library: zig links its own, so gd compiles the library
// from this source instead, alongside the engine (see android_engine.go).
//
//   - src/ holds the C++ sources, flattened: games-frame-pacing/{common,
//     opengl,vulkan}, the shared src/common helpers and the public headers
//     under include/swappy. One edit is made to ChoreographerShim.h: its
//     function pointer typedefs for the API 33 choreographer functions are
//     removed, as the (newer) NDK headers gd bundles declare the functions
//     themselves and the code never uses the typedefs.
//   - classes.dex holds the two Java classes the library loads at runtime
//     on Android 9 to 11 (ChoreographerCallback and SwappyDisplayManager),
//     which on those versions stand in for choreographer APIs the NDK only
//     gained in API 31. The library embeds the dex file and loads it with
//     an in-memory class loader, as the upstream build does. The classes
//     are compiled by javac against signature-only stubs of the platform
//     classes they refer to (written here, nothing is taken from the SDK's
//     android.jar) and converted by d8, from Google's open source R8.
//
// javac needs a JDK 11 or later on PATH (JAVA_HOME is honoured), d8 is
// fetched from maven.google.com.
package main

