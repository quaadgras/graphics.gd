func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-swappy:", err)
		os.Exit(1)
	}
}

func generate() error {
	root, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}").Output()
	if err != nil {
		return err
	}
	out := filepath.Join(strings.TrimSpace(string(root)), "cmd", "gd", "internal", "builder", "bundled", "swappy")
	work, err := os.MkdirTemp("", "gen-swappy")
	if err != nil {
		return err
	}
	defer os.RemoveAll(work)
	repo := filepath.Join(work, "gamesdk")
	if err := fetch(repo); err != nil {
		return err
	}
	if err := os.RemoveAll(out); err != nil {
		return err
	}
	src := filepath.Join(out, "src")
	for _, source := range sources {
		if err := flatten(filepath.Join(repo, filepath.FromSlash(source)), src, out); err != nil {
			return err
		}
	}
	if err := patchShim(filepath.Join(src, "ChoreographerShim.h")); err != nil {
		return err
	}
	if err := dex(work, repo, filepath.Join(out, "classes.dex")); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "README.txt"), []byte(readme), 0644)
}

const readme = `Swappy, the frame pacing library of the Android Game SDK.

Upstream: https://android.googlesource.com/platform/frameworks/opt/gamesdk/
Version:  ` + commit + `
License:  Apache 2.0 (LICENSE)

Generated by ../gen-swappy, which documents what is here and the one edit
made to ChoreographerShim.h; do not edit by hand.
`

// fetch makes a sparse, shallow checkout of the gamesdk at the commit.
func fetch(dst string) error {
	if err := os.MkdirAll(dst, 0755); err != nil {
		return err
	}
	git := func(args ...string) error {
		cmd := exec.Command("git", append([]string{"-C", dst}, args...)...)
		cmd.Stderr = os.Stderr
		return cmd.Run()
	}
	fmt.Println("gen-swappy: fetching gamesdk")
	sparse := []string{"/games-frame-pacing/", "/src/common/", "/include/", "/LICENSE"}
	for _, args := range [][]string{
		{"init", "-q"},
		{"remote", "add", "origin", gamesdk},
		{"sparse-checkout", "set", "--no-cone"},
		append([]string{"sparse-checkout", "add"}, sparse...),
		{"fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", commit},
		{"checkout", "-q", "FETCH_HEAD"},
	} {
		if err := git(args...); err != nil {
			return err
		}
	}
	return nil
}

// flatten copies a source file, or every file of a source directory, into
// src: the sources include each other by bare name, the public headers by
// swappy/name, which keep their directory. The LICENSE goes beside src.
func flatten(path, src, out string) error {
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		dst := filepath.Join(src, filepath.Base(path))
		switch {
		case filepath.Base(path) == "LICENSE":
			dst = filepath.Join(out, "LICENSE")
		case strings.Contains(filepath.ToSlash(path), "/include/swappy/"):
			dst = filepath.Join(src, "swappy", filepath.Base(path))
		case strings.Contains(filepath.ToSlash(path), "/include/common/"):
			dst = filepath.Join(src, "common", filepath.Base(path))
		}
		return copyFile(path, dst)
	}
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if err := copyFile(filepath.Join(path, entry.Name()), filepath.Join(src, entry.Name())); err != nil {
			return err
		}
	}
	return nil
}

func copyFile(from, to string) error {
	data, err := os.ReadFile(from)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(to), 0755); err != nil {
		return err
	}
	return os.WriteFile(to, data, 0644)
}

// patchShim removes the function pointer typedefs that ChoreographerShim.h
// declares for API levels below 33, which clash with the declarations of
// the functions themselves in the newer choreographer.h that gd bundles.
// Nothing uses them: ChoreographerThread.cpp declares its own PFN_ types.
func patchShim(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	text := string(data)
	start := strings.Index(text, "/**\n * Posts a callback to be run when the application should begin rendering the\n * next frame.")
	end := strings.Index(text, "#endif  // __ANDROID_API__ < 33")
	if start < 0 || end < start {
		return fmt.Errorf("%s: cannot find the API 33 function pointer typedefs to remove", path)
	}
	return os.WriteFile(path, []byte(text[:start]+text[end:]), 0644)
}

// dex compiles the Java classes the library loads at runtime.
func dex(work, repo, out string) error {
	stubs := filepath.Join(work, "stubs")
	for name, source := range androidStubs {
		path := filepath.Join(stubs, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(source), 0644); err != nil {
			return err
		}
	}
	javac, jav := "javac", "java"
	if home := os.Getenv("JAVA_HOME"); home != "" {
		javac, jav = filepath.Join(home, "bin", "javac"), filepath.Join(home, "bin", "java")
	}
	classes := filepath.Join(work, "classes")
	if err := os.MkdirAll(classes, 0755); err != nil {
		return err
	}
	var files []string
	for _, source := range java {
		files = append(files, filepath.Join(repo, filepath.FromSlash(source)))
	}
	for name := range androidStubs {
		files = append(files, filepath.Join(stubs, filepath.FromSlash(name)))
	}
	fmt.Println("gen-swappy: compiling java classes")
	// Android 9 (API 28) is the oldest version that loads the classes.
	cmd := exec.Command(javac, append([]string{"--release", "8", "-Xlint:-options", "-d", classes}, files...)...)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("javac: %w", err)
	}
	jar := filepath.Join(work, "r8.jar")
	if err := download(r8, jar); err != nil {
		return err
	}
	fmt.Println("gen-swappy: converting to dex")
	var inputs []string
	for _, source := range java {
		name := strings.TrimSuffix(filepath.Base(source), ".java")
		matches, _ := filepath.Glob(filepath.Join(classes, "com", "google", "androidgamesdk", name+"*.class"))
		inputs = append(inputs, matches...)
	}
	dexed := filepath.Join(work, "dex")
	if err := os.MkdirAll(dexed, 0755); err != nil {
		return err
	}
	cmd = exec.Command(jav, append([]string{"-cp", jar, "com.android.tools.r8.D8", "--release", "--min-api", "28", "--output", dexed}, inputs...)...)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("d8: %w", err)
	}
	return copyFile(filepath.Join(dexed, "classes.dex"), out)
}

func download(url, path string) error {
	fmt.Println("gen-swappy: downloading", url)
	resp, err := http.Get(url)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", url, resp.Status)
	}
	file, err := os.Create(path)
	if err != nil {
		return err
	}
	defer file.Close()
	_, err = io.Copy(file, resp.Body)
	return err
}

